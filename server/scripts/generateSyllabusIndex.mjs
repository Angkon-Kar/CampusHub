// server/scripts/generateSyllabusIndex.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const clientUtil = process.argv[2] || path.resolve(here, '../../client/src/utils/subjects.js');
const output = path.resolve(here, '../data/syllabusIndex.js');

const { getSubjectOptions, DEPARTMENTS_WITH_SYLLABUS, SEMESTER_COUNT } = await import(pathToFileURL(clientUtil).href);

const index = Object.fromEntries(
  DEPARTMENTS_WITH_SYLLABUS.map((department) => [
    department,
    Object.fromEntries(
      Array.from({ length: SEMESTER_COUNT }, (_, i) => [
        i + 1,
        getSubjectOptions(department, i + 1).map(({ code, name }) => ({ code, name })),
      ])
    ),
  ])
);

const file = `// server/data/syllabusIndex.js
// GENERATED by scripts/generateSyllabusIndex.mjs from the client's syllabusData.js. Do not edit by hand.
export const SEMESTER_COUNT = ${SEMESTER_COUNT};

export const SYLLABUS_INDEX = ${JSON.stringify(index, null, 1)};

export const SYLLABUS_DEPARTMENTS = Object.keys(SYLLABUS_INDEX);

// Returns { code, name } when the subject belongs to that department and semester, otherwise null
export const findSubject = (department, semester, code) =>
  SYLLABUS_INDEX[department]?.[Number(semester)]?.find((subject) => subject.code === code) ?? null;
`;

fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, file);
console.log(`Wrote ${output} (${Math.round(file.length / 1024)} KB)`);
